/** Returns `t(key)`, falling back to `defaultLang` and then to the key itself. */
export function useTranslations(lang) {
  const dictionary = ui[lang] ?? ui[defaultLang];
  return function t(key) {
    return dictionary[key] ?? ui[defaultLang][key] ?? key;
  };
}
